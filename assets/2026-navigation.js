(()=>{'use strict';
const nav=document.querySelector('.topbar .nav');
const links=nav?.querySelector('.navlinks');
if(!nav||!links||nav.querySelector('.nav-toggle'))return;
const button=document.createElement('button');
button.type='button';
button.className='btn ghost nav-toggle';
button.setAttribute('aria-controls','hte-primary-navigation');
button.setAttribute('aria-expanded','false');
button.setAttribute('aria-label','Open navigation menu');
button.innerHTML='<span aria-hidden="true">☰</span><span>Menu</span>';
links.id='hte-primary-navigation';
nav.insertBefore(button,links);
const close=()=>{links.classList.remove('is-open');button.setAttribute('aria-expanded','false');button.setAttribute('aria-label','Open navigation menu');button.innerHTML='<span aria-hidden="true">☰</span><span>Menu</span>'};
button.addEventListener('click',()=>{const open=button.getAttribute('aria-expanded')!=='true';links.classList.toggle('is-open',open);button.setAttribute('aria-expanded',String(open));button.setAttribute('aria-label',open?'Close navigation menu':'Open navigation menu');button.innerHTML=open?'<span aria-hidden="true">×</span><span>Close</span>':'<span aria-hidden="true">☰</span><span>Menu</span>'});
links.addEventListener('click',event=>{if(event.target.closest('a'))close()});
document.addEventListener('keydown',event=>{if(event.key==='Escape')close()});
document.addEventListener('click',event=>{if(!nav.contains(event.target))close()});
window.addEventListener('resize',()=>{if(window.innerWidth>980)close()},{passive:true});
})();